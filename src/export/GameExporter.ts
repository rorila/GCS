    /**
     * Compress project JSON using gzip and encode as Base64
     */
    private compressProject(project: any): string {
        const json = JSON.stringify(project);
        const compressed = gzipSync(new TextEncoder().encode(json));
        // Convert Uint8Array to Base64
        let binary = '';
        for (let i = 0; i < compressed.length; i++) {
            binary += String.fromCharCode(compressed[i]);
        }
        return btoa(binary);
    }

    /** Helfer zum sicheren Serialisieren von Objekten mit zirkulären Referenzen (z.B. Editor-Instanzen) */
    private safeStringify(obj: any): string {
        const seen = new WeakSet();
        const SKIP_KEYS = new Set(['renderer', 'host', 'parent', 'stage', 'editor', '__rawSource', '_listeners', '_eventTarget']);
        return JSON.stringify(obj, (key: string, value: any) => {
            if (SKIP_KEYS.has(key)) return undefined;
            if (typeof value === 'object' && value !== null) {
                if (seen.has(value)) return undefined;
                seen.add(value);
            }
            return value;
        });
    }

    /**
     * Removes all editor-only properties (flow editor, node positions, etc.)
     * to keep the game file small and clean for the platform.
     */
    public getCleanProject(project: GameProject): any {
        // 1. Whitelist for top-level keys
        const whitelist = ['meta', 'stages', 'activeStageId', 'variables', 'tasks', 'actions', 'stage', 'objects', 'flowCharts', 'splashAutoHide', 'splashDuration', 'themes', 'activeThemeId'];

        const clean: any = {};
        whitelist.forEach(key => {
            if ((project as any)[key] !== undefined) {
                // Nutze safeStringify, um TypeError bei zirkulären Laufzeit-Referenzen (parent, editor) zu verhindern
                clean[key] = JSON.parse(this.safeStringify((project as any)[key]));
            }
        });

        // 2. Recursive deep clean
        this.deepClean(clean);

        // 3. Specialized cleaning for Stages
        if (clean.stages) {
            // Variables are kept in objects intentionally.
        }

        // 4. Add meta info for platform
        if (!clean.meta) clean.meta = {};
        const mainStage = clean.stages?.find((s: any) => s.type === 'main');
        if (mainStage) {
            if (mainStage.gameName) clean.meta.name = mainStage.gameName;
            if (mainStage.author) clean.meta.author = mainStage.author;
            if (mainStage.description) clean.meta.description = mainStage.description;
        }

        clean.meta.exportedAt = new Date().toISOString();
        clean.meta.type = 'standalone_game';
        clean.meta.runtimeVersion = RUNTIME_VERSION;

        return clean;
    }

    /**
     * Recursively removes internal properties and editor-only noise
     */
    private deepClean(obj: any): void {
        if (!obj || typeof obj !== 'object') return;

        if (Array.isArray(obj)) {
            obj.forEach(item => this.deepClean(item));
            return;
        }

        // ACHTUNG: flowCharts, tasks und connections sind RUNTIME-RELEVANT!
        // Sie enthalten die Task-Sequenzen für Spiel-Logik (Bounce, Score, Navigation).
        // Nur echte Editor-Metadaten entfernen:
        const editorOnlyKeys = ['flow', 'flowGraph', 'nodePositions', 'description', 'details', 'showDetails'];

        Object.keys(obj).forEach(key => {
            // Remove keys in editor-only list or known noisy internal React/Vue keys
            if (editorOnlyKeys.includes(key) || key === '__v_isRef' || key === '__v_raw') {
                delete obj[key];
            } else {
                this.deepClean(obj[key]);
            }
        });
    }

