    /**
     * Trigger file download.
     * Unterstützt: Electron (window.electronFS) > FileSystem Access API > Blob-Download.
     */
    private async downloadFile(content: string, filename: string, mimeType: string): Promise<void> {
        // 1. Electron-Modus (IPC-Bridge) inkl native Dialog
        if ((window as any).electronFS) {
            try {
                const ext = mimeType === 'text/html' ? 'html' : 'json';
                const fileType = mimeType === 'text/html' ? 'HTML Game' : 'JSON Game Project';
                const targetPath = await (window as any).electronFS.showSaveDialog({
                    defaultPath: filename,
                    filters: [{ name: fileType, extensions: [ext] }]
                });
                
                if (!targetPath) return; // User canceled
                
                await (window as any).electronFS.writeFile(targetPath, content);
                NotificationToast.show(`Export erfolgreich!\n\nDatei: ${targetPath}`);
                return;
            } catch (err) {
                logger.warn('Electron FS failed, falling back:', err);
            }
        }

        // 2. FileSystem Access API (modern browsers)
        if ('showSaveFilePicker' in window) {
            try {
                const handle = await (window as any).showSaveFilePicker({
                    suggestedName: filename,
                    types: [{
                        description: mimeType === 'text/html' ? 'HTML Game File' : 'JSON Game File',
                        accept: { [mimeType]: [mimeType === 'text/html' ? '.html' : '.json'] }
                    }]
                });
                const writable = await handle.createWritable();
                await writable.write(content);
                await writable.close();
                NotificationToast.show(`Game exported successfully!\n\nFile: ${handle.name}\n\nOpen it in any browser to play.`);
                return;
            } catch (err: any) {
                if (err.name === 'AbortError') return;
                logger.warn('File System Access API failed, using fallback:', err);
            }
        }

        // 3. Fallback: Blob-Download
        const blob = new Blob([content], { type: mimeType });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = filename;
        a.style.display = 'none';
        document.body.appendChild(a);
        a.click();
        setTimeout(() => document.body.removeChild(a), 2000);
        NotificationToast.show(`Game exported to Downloads folder.\n\nFile: ${filename}`);
    }

