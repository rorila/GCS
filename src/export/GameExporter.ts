    /**
     * Finds and embeds all media references (Images, Audio) in the project as Base64 Data URLs.
     */
    private async embedMedia(project: any): Promise<void> {
        const mediaRefs = new Map<string, string>(); // path -> dataUrl

        const mediaExtensions = /\.(png|jpg|jpeg|gif|svg|webp|bmp|ico|mp3|ogg|wav|mp4|webm)$/i;
        const isMediaPath = (s: string) => {
            if (!s || typeof s !== 'string' || s.length === 0) return false;
            if (s.startsWith('data:') || s.startsWith('http://') || s.startsWith('https://')) return false;
            return (/(^|\/)(images|audio|video|assets)\//i).test(s) || mediaExtensions.test(s);
        };

        // Build a map of known variables and lists for resolving ${...} bindings
        const varMap = new Map<string, any>();
        const collectVariables = (obj: any) => {
            if (Array.isArray(obj)) {
                obj.forEach(collectVariables);
                return;
            }
            if (!obj || typeof obj !== 'object') return;
            if ((obj.className === 'TVariable' || obj.className === 'Variable') && typeof obj.name === 'string') {
                varMap.set(obj.name, obj.value);
            }
            if ((obj.className === 'TListVariable' || obj.className === 'ListVariable') && typeof obj.name === 'string' && Array.isArray(obj.items)) {
                varMap.set(obj.name, obj.items);
            }
            Object.values(obj).forEach(collectVariables);
        };
        collectVariables(project);

        const resolveBinding = (s: string, depth = 3): string | undefined => {
            if (typeof s !== 'string') return undefined;
            const m = s.match(/^\s*\$\{([^}]+)\}\s*$/);
            if (!m || depth <= 0) return undefined;
            const expr = m[1].trim();

            // Array index access: List_15[0]
            const idxMatch = expr.match(/^([A-Za-z_][A-Za-z0-9_]*)\s*\[\s*(\d+)\s*\]$/);
            if (idxMatch) {
                const list = varMap.get(idxMatch[1]);
                if (Array.isArray(list)) {
                    const resolved = list[parseInt(idxMatch[2], 10)];
                    if (typeof resolved === 'string' && resolved) {
                        return resolveBinding(resolved, depth - 1) ?? resolved;
                    }
                    return typeof resolved === 'string' ? resolved : undefined;
                }
                return undefined;
            }

            const val = varMap.get(expr);
            if (typeof val === 'string' && val) return resolveBinding(val, depth - 1) ?? val;
            if (typeof val === 'string') return val;
            if (val !== undefined && val !== null) return String(val);
            return undefined;
        };

        // 1. Collect all unique media paths from the project recursively
        const collectPaths = (obj: any) => {
            const tryCollect = (s: string) => {
                if (isMediaPath(s)) {
                    mediaRefs.set(s, '');
                } else {
                    const resolved = resolveBinding(s);
                    if (typeof resolved === 'string' && isMediaPath(resolved)) {
                        mediaRefs.set(resolved, '');
                    }
                }
            };
            if (Array.isArray(obj)) {
                obj.forEach((item: any) => {
                    if (typeof item === 'string') {
                        tryCollect(item);
                    } else if (item && typeof item === 'object') {
                        collectPaths(item);
                    }
                });
                return;
            }
            if (!obj || typeof obj !== 'object') return;

            Object.values(obj).forEach((val: any) => {
                if (typeof val === 'string') {
                    tryCollect(val);
                } else if (val && typeof val === 'object') {
                    collectPaths(val);
                }
            });
        };

        collectPaths(project);

        // 2. Fetch and convert to Base64
        logger.info(`[GameExporter] Found ${mediaRefs.size} unique media files to embed.`);
        for (const [path, _] of mediaRefs) {
            try {
                // Strip leading / or ./ so the path is always relative to the app root
                let relativePath = path;
                if (relativePath.startsWith('./')) {
                    relativePath = relativePath.substring(2);
                }
                if (relativePath.startsWith('/')) {
                    relativePath = relativePath.substring(1);
                }
                const baseUrl = project.meta?.baseUrl || network.getHttpUrl() || window.location.href;
                const url = new URL(relativePath, baseUrl).href;

                const urls = [url];
                if (!relativePath.startsWith('images/')) {
                    urls.push(new URL(`images/${relativePath}`, baseUrl).href);
                }

                let embedded = false;
                for (const tryUrl of urls) {
                    logger.info(`[GameExporter] Fetching media: ${tryUrl}`);
                    const resp = await fetch(tryUrl);
                    if (resp.ok) {
                        const contentType = resp.headers.get('content-type') || '';
                        if (contentType.includes('text/html')) {
                            logger.warn(`[GameExporter] Media path returned HTML, not a media file: ${tryUrl}`);
                        } else {
                            const blob = await resp.blob();
                            const dataUrl = await this.blobToDataUrl(blob);
                            mediaRefs.set(path, dataUrl);
                            logger.info(`[GameExporter] Successfully embedded: ${path} from ${tryUrl}`);
                            embedded = true;
                            break;
                        }
                    }
                }
                if (!embedded) {
                    logger.warn(`[GameExporter] Failed to embed media: ${path}`);
                }
            } catch (e) {
                logger.warn(`[GameExporter] Network error embedding media: ${path}`, e);
            }
        }

        // 3. Replace paths with Data URLs in the project recursively
        const replacePaths = (obj: any) => {
            if (Array.isArray(obj)) {
                obj.forEach((item: any, i: number) => {
                    if (typeof item === 'string' && mediaRefs.has(item)) {
                        const dataUrl = mediaRefs.get(item);
                        if (dataUrl) obj[i] = dataUrl;
                    } else if (item && typeof item === 'object') {
                        replacePaths(item);
                    }
                });
                return;
            }
            if (!obj || typeof obj !== 'object') return;

            Object.keys(obj).forEach(key => {
                const val = obj[key];
                if (typeof val === 'string' && mediaRefs.has(val)) {
                    const dataUrl = mediaRefs.get(val);
                    if (dataUrl) obj[key] = dataUrl;
                } else if (val && typeof val === 'object') {
                    replacePaths(val);
                }
            });
        };

        replacePaths(project);
    }

    /**
     * Convert a Blob to a Base64 Data URL
     */
    private blobToDataUrl(blob: Blob): Promise<string> {
        return new Promise((resolve, reject) => {
            const reader = new FileReader();
            reader.onloadend = () => resolve(reader.result as string);
            reader.onerror = reject;
            reader.readAsDataURL(blob);
        });
    }

