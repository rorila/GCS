import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
const require=createRequire(import.meta.url), out='artifacts/user-guide-verification';
const results=JSON.parse(fs.readFileSync(path.join(out,'results.json'),'utf8'));
assert.equal(results.results.length,8);
assert.ok(results.results.every(r=>['passed','passed-with-deviations'].includes(r.status)));
assert.deepEqual(results.errors,[]);
const meta=JSON.parse(fs.readFileSync(path.join(out,'video-metadata.json'),'utf8'));
const duration=Number(meta.format.duration);assert.ok(duration>=30&&duration<=90);
execFileSync(require('ffmpeg-static'),['-y','-i',path.join(out,'pilot-neues-projekt.mp4'),'-vf',"select='eq(n,50)+eq(n,400)+eq(n,800)',scale=640:-1,tile=3x1",'-frames:v','1',path.join(out,'video-contact.png')],{windowsHide:true,stdio:'ignore'});
const digest=f=>createHash('sha256').update(fs.readFileSync(f)).digest('hex');
const walk=d=>fs.readdirSync(d,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.join(d,e.name)):[path.join(d,e.name).replaceAll('\\','/')]);
const audit=JSON.parse(fs.readFileSync(path.join(out,'source-integrity.json'),'utf8'));
const current=Object.fromEntries([...walk('src'),...walk('docs/user-guide')].map(f=>[f,digest(f)]));
audit.changedExisting=Object.keys(audit.files).filter(f=>current[f]&&current[f]!==audit.files[f]);
audit.removed=Object.keys(audit.files).filter(f=>!(f in current));
audit.added=Object.keys(current).filter(f=>!(f in audit.files));
audit.existingUnchanged=!audit.changedExisting.length&&!audit.removed.length;
audit.unchanged=audit.existingUnchanged&&!audit.added.length;
const requested=f=>f.startsWith('src/')||/^docs\/user-guide\/kapitel-0[1-5]-/.test(f);
audit.requestedScopeChanged=[...audit.changedExisting,...audit.removed].filter(requested);
audit.requestedScopeUnchanged=!audit.requestedScopeChanged.length;
assert.equal(audit.requestedScopeUnchanged,true,'Anwendungsquellen oder Kapitel 1–5 wurden während der Prüfung verändert');
fs.writeFileSync(path.join(out,'source-integrity.json'),JSON.stringify(audit,null,2));
fs.writeFileSync(path.join(out,'source-changes.json'),JSON.stringify({changedExisting:audit.changedExisting,added:audit.added,removed:audit.removed},null,2));
const md=fs.readFileSync(path.join(out,'REPORT.md'),'utf8');
const missing=[...md.matchAll(/\]\(([^)]+)\)/g)].map(m=>m[1]).filter(f=>!fs.existsSync(path.resolve(out,f)));
assert.deepEqual(missing,[],'Berichtslinks fehlen');
const summary={completedSteps:results.results.length,stepsWithDeviations:results.results.filter(r=>r.status==='passed-with-deviations').length,deviations:results.deviations.length,pageErrors:results.errors.length,videoSeconds:duration,requestedScopeUnchanged:audit.requestedScopeUnchanged,unchangedExistingFileCount:Object.keys(audit.files).length-audit.changedExisting.length-audit.removed.length,otherChangedFiles:audit.changedExisting,additionalFilesDuringRun:audit.added};
fs.writeFileSync(path.join(out,'run-summary.json'),JSON.stringify(summary,null,2));
const files=[...fs.readdirSync(out).filter(f=>/\.(png|mp4|webm|json|md|zip)$/.test(f)&&f!=='checksums.json').map(f=>path.join(out,f)),...['verify.mjs','qa.mjs','README.md'].map(f=>path.join('scripts/user-guide',f))];
fs.writeFileSync(path.join(out,'checksums.json'),JSON.stringify(Object.fromEntries(files.map(f=>[f.replaceAll('\\','/'),digest(f)])),null,2));
console.log(JSON.stringify(summary,null,2));
